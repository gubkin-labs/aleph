//! Repository automation.
//!
//! `cargo xtask codegen` regenerates the manifest contract from the Rust types:
//! - `schema/manifest.schema.json`: JSON Schema for third-party SDKs and platforms
//! - `packages/manifest/src/generated/` and `generated.ts`: TypeScript types for `@aleph/manifest`
//!
//! `cargo xtask codegen --check` fails if the committed files are stale (used in CI).

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use aleph_core::check::CheckReport;
use aleph_core::{Diagnostic, Limits, Manifest, Request, Response};
use ts_rs::{Config, TS};

const BANNER: &str = "// Generated by `cargo xtask codegen` from crates/aleph-core. Do not edit.\n";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("codegen") => match codegen(args.iter().any(|a| a == "--check")) {
            Ok(()) => ExitCode::SUCCESS,
            Err(message) => {
                eprintln!("{message}");
                ExitCode::FAILURE
            }
        },
        _ => {
            eprintln!("usage: cargo xtask codegen [--check]");
            ExitCode::FAILURE
        }
    }
}

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn codegen(check: bool) -> Result<(), String> {
    let root = root();
    let mut files: Vec<(PathBuf, String)> = Vec::new();

    let schema = schemars::schema_for!(Manifest);
    let schema_json = serde_json::to_string_pretty(&schema).map_err(|e| e.to_string())?;
    files.push((root.join("schema/manifest.schema.json"), schema_json + "\n"));

    let scratch = std::env::temp_dir().join(format!("aleph-codegen-{}", std::process::id()));
    let _ = fs::remove_dir_all(&scratch);
    let cfg = Config::new()
        .with_out_dir(&scratch)
        .with_large_int("number")
        .with_import_extension(Some("js"));
    Manifest::export_all(&cfg).map_err(|e| e.to_string())?;
    CheckReport::export_all(&cfg).map_err(|e| e.to_string())?;
    Diagnostic::export_all(&cfg).map_err(|e| e.to_string())?;
    Limits::export_all(&cfg).map_err(|e| e.to_string())?;
    Request::export_all(&cfg).map_err(|e| e.to_string())?;
    Response::export_all(&cfg).map_err(|e| e.to_string())?;

    let generated = root.join("packages/manifest/src/generated");
    let mut names: Vec<String> = Vec::new();
    for entry in fs::read_dir(&scratch).map_err(|e| e.to_string())? {
        let path = entry.map_err(|e| e.to_string())?.path();
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .ok_or("bad file name")?
            .to_owned();
        let body = fs::read_to_string(&path).map_err(|e| e.to_string())?;
        // ts-rs writes its own header comment; replace it with ours so the files are stable.
        let body: String = body
            .lines()
            .filter(|l| !l.starts_with("// This file was generated"))
            .collect::<Vec<_>>()
            .join("\n");
        files.push((
            generated.join(&name),
            format!("{BANNER}{}\n", body.trim_start()),
        ));
        names.push(name);
    }
    let _ = fs::remove_dir_all(&scratch);
    names.sort();
    let mut index = String::new();
    for name in &names {
        let _ = writeln!(
            index,
            "export type * from \"./generated/{}.js\";",
            name.trim_end_matches(".ts")
        );
    }
    // The barrel lives next to the directory: `generated/index.ts` would collide with `Index.ts` on
    // case-insensitive filesystems.
    files.push((
        root.join("packages/manifest/src/generated.ts"),
        format!("{BANNER}{index}"),
    ));

    if check {
        let mut stale = Vec::new();
        for (path, content) in &files {
            if fs::read_to_string(path).ok().as_deref() != Some(content.as_str()) {
                stale.push(path.display().to_string());
            }
        }
        if let Ok(existing) = fs::read_dir(&generated) {
            for entry in existing.flatten() {
                if !files.iter().any(|(p, _)| *p == entry.path()) {
                    stale.push(format!("{} (no longer generated)", entry.path().display()));
                }
            }
        }
        if !stale.is_empty() {
            return Err(format!(
                "generated files are stale, run `pnpm codegen`:\n  {}",
                stale.join("\n  ")
            ));
        }
        return Ok(());
    }

    let _ = fs::remove_dir_all(&generated);
    for (path, content) in &files {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    println!("wrote {} files", files.len());
    Ok(())
}
